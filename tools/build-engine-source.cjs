/* Build or verify the file:// source bundle from the engine loader's shipped file list. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const loader = fs.readFileSync(path.join(root, 'js/mods.js'), 'utf8');
const start = loader.indexOf('const engineScripts=');
const end = loader.indexOf('const engineDependencies=', start);
if (start < 0 || end < 0) throw new Error('Could not find the engine source list in js/mods.js.');
const sourcePaths = vm.runInNewContext(loader.slice(start, end) + '\nengineFiles;');
const enginePaths = [...sourcePaths, 'js/mod-game.js', 'js/mod-game.css'];
const files = Object.fromEntries(enginePaths.map(relativePath => {
  const bytes = fs.readFileSync(path.join(root, relativePath));
  const content = relativePath.endsWith('.webp')
    ? { type: 'image/webp', base64: bytes.toString('base64') }
    : bytes.toString('utf8');
  return [relativePath, content];
}));
const output = path.join(root, 'js/engine-source.js');
const script = '/* Generated by node tools/build-engine-source.cjs. Source files are indexed in docs/source-index.md. */\n'
  + 'window.SD_BUNDLED_ENGINE_SOURCE = ' + JSON.stringify(files, null, 1) + ';\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== script) throw new Error('The engine bundle is out of date. Run node tools/build-engine-source.cjs.');
} else {
  fs.writeFileSync(output, script);
}
console.log(enginePaths.length + ' game files ' + (process.argv.includes('--check') ? 'verified.' : 'packaged.'));
